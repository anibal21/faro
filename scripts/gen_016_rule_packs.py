def rule(
    rid,
    sev,
    contains,
    summary,
    why,
    look,
    recs,
    title=None,
    allc=None,
    tags=None,
):
    return {
        "id": rid,
        "severity": sev,
        "match_contains": contains,
        "match_all_contains": allc or [],
        "title": title or rid.split(".")[-1].replace("_", " ").title(),
        "summary": summary,
        "why": why,
        "whatToLookFor": look,
        "recommendation": recs if isinstance(recs, list) else [recs],
        "tags": tags or [],
    }


