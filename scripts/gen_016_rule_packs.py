def write_pack(pid, name, rules):
    d = os.path.join(root, pid)
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, "default.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"id": pid, "displayName": name, "rules": rules}, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{pid}: {len(rules)} rules -> {path}")


